"""Bundle the shared JSON content and audio into the web build.

    python tools/build_web.py

Writes web/js/content.js (window.BUA_CONTENT = {...}) so the web game runs
from a plain double-click on web/index.html with no server and no fetch, and
copies assets/audio (ogg/wav + voice clips) into web/assets/audio.
"""
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTENT = ROOT / "game" / "content"
WEB = ROOT / "web"


def main():
    bundle = {}
    for name in ("scenes", "items", "dialogue", "quests", "characters"):
        with open(CONTENT / f"{name}.json", encoding="utf-8") as fh:
            bundle[name] = json.load(fh)
    out = WEB / "js" / "content.js"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("// GENERATED by tools/build_web.py from game/content/*.json. Do not edit.\n"
                   "window.BUA_CONTENT = " + json.dumps(bundle, ensure_ascii=False, indent=1) + ";\n",
                   encoding="utf-8")
    src = ROOT / "assets" / "audio"
    dst = WEB / "assets" / "audio"
    dst.mkdir(parents=True, exist_ok=True)
    copied = 0
    for p in src.rglob("*"):
        if p.suffix.lower() in (".ogg", ".wav", ".mp3", ".m4a"):
            target = dst / p.relative_to(src)
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(p, target)
            copied += 1
    voices = sorted({p.stem for p in (src / "voice").glob("*") if p.suffix.lower() in (".ogg", ".wav", ".mp3", ".m4a")}) if (src / "voice").is_dir() else []
    (WEB / "js" / "voice_index.js").write_text("// GENERATED by tools/build_web.py: voice clips present in assets/audio/voice.\n"
                                               "window.BUA_VOICES = " + json.dumps(voices) + ";\n", encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)} ({out.stat().st_size // 1024} KB), copied {copied} audio files")


if __name__ == "__main__":
    main()
